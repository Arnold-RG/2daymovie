def all_poems() -> list[dict]:
    return list(POEMS)


def get_poem(slug: str) -> dict | None:
    for poem in POEMS:
        if poem["slug"] == slug:
            return poem
    return None


def featured_poem() -> dict:
    return POEMS[0]


def moods() -> list[str]:
    seen: list[str] = []
    for poem in POEMS:
        mood = poem.get("mood")
        if mood and mood not in seen:
            seen.append(mood)
    return seen
