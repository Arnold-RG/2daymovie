def all_years() -> list[int]:
    return sorted(YEAR_MOVIES.keys(), reverse=True)


def titles_for_year(year: int) -> list[str]:
    return list(YEAR_MOVIES.get(year, []))


def total_titles() -> int:
    return sum(len(v) for v in YEAR_MOVIES.values())
